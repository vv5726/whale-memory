from PIL import Image, ImageDraw, ImageFont
W, H = 1500, 980
BG, FG, DIM = (16, 19, 25), (232, 236, 244), (150, 158, 172)
ACC, GOOD, WARN = (96, 200, 255), (120, 220, 160), (235, 190, 120)
F, FB = "C:/Windows/Fonts/msyh.ttc", "C:/Windows/Fonts/msyhbd.ttc"
def f(s, b=False): return ImageFont.truetype(FB if b else F, s)

img = Image.new("RGB", (W, H), BG)
d = ImageDraw.Draw(img)
d.text((50, 40), "「无限上下文」是怎么做的", font=f(44, True), fill=FG)
d.text((50, 100), "不靠更长的窗口，靠四件事：抽出来、分层、会忘、按需取回", font=f(22), fill=ACC)

def box(x, y, w, h, title, sub, color=FG, fill=(28, 33, 42)):
    d.rounded_rectangle([x, y, x + w, y + h], 14, fill=fill, outline=(54, 62, 76), width=2)
    d.text((x + 18, y + 14), title, font=f(23, True), fill=color)
    for i, s in enumerate(sub):
        d.text((x + 18, y + 50 + i * 27), s, font=f(18), fill=DIM)

