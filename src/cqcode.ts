/** 把一条消息里的 CQ 码换成人类能读的描述 */
export function describeCqCodes(text: string): string {
  let out = String(text ?? "");

  // 表情：[CQ:face,id=467,...] → （表情：摇花手）
  // 同一个 id 只认一次：NapCat 有时一个表情给两段（face 段重复），
  // 以前会变成「发了个表情：流泪」两遍，它读完以为对方连发两次。
  const seenFaceIds = new Set<string>();
  out = out.replace(/\[CQ:face,id=(\d+)([^\]]*)\]/g, (_m, id: string, rest: string) => {
    if (seenFaceIds.has(id)) return "";
    seenFaceIds.add(id);
    const name = QQ_FACES[id];
    // NapCat 有时会把表情名放在 faceText 里，优先用它
    const faceText = /faceText=([^,\]]*)/.exec(rest)?.[1]?.replace(/^\/+/, "").trim();
    if (name) return `[发了个表情：${name}]`;
    if (faceText) return `[发了个表情：${faceText}]`;
    // 表里没有、也没名字：只说「发了个表情」，不要把 id 甩给它
    return "[发了个表情]";
  });

  // 小表情 / 魔法表情
  out = out.replace(/\[CQ:mface[^\]]*\]/g, "（表情）");

  // 语音
  out = out.replace(/\[CQ:record[^\]]*\]/g, "（语音，听不了）");

  // 图片：带上 summary，那是 QQ 自己给的文字摘要
  out = out.replace(/\[CQ:image,([^\]]*)\]/g, (_m, attrs: string) => {
    const summary = /summary=([^,\]]*)/.exec(attrs)?.[1];
    const face = /faceText=([^,\]]*)/.exec(attrs)?.[1];
    const label = face ? face.replace(/&amp;/g, "") : summary ? summary.replace(/&#91;|&#93;/g, "") : "";
    return label ? `[发了张图：${label}]` : "[发了张图，看不到内容]";
  });

  // 连着两个同样的表情（NapCat 会同时给 face 段和表情字符）→ 只留一个
  out = out.replace(/(\[发了个表情[^\]]*\])\s*\1/g, "$1");

  // @ 和回复
  out = out.replace(/\[CQ:at,qq=(\w+)[^\]]*\]/g, "@$1 ");
  out = out.replace(/\[CQ:reply[^\]]*\]/g, "");

  // 剩下的杂项一律去掉
  out = out.replace(/\[CQ:[^\]]*\]/g, "");

  return out.replace(/\s+/g, " ").trim();
}

/** 这条消息里有没有表情/图片（用来判断要不要特别处理） */
export function hasRichContent(text: string): boolean {
  return /\[CQ:(face|mface|image)/.test(String(text ?? ""));
}
