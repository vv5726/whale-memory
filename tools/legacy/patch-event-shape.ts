import { readFileSync, writeFileSync } from "node:fs";

const p = "src/llm/extract.ts";
let s = readFileSync(p, "utf8");

// 规则 2 / 3 重写：要「一件事」，不要「他说…她说…」的流水
const oldRule2 = `    "2. title 是将来检索这条记忆的唯一钥匙（正文会被逐步压缩掉），所以它必须包含",
    "   这条记忆最独特的检索词：具体人名、物件、金额、日期、结论，而不是抽象概括。",
    "   好例子：「王建国欠两千块下周还」「团子肾不好要长期打针」「病理结果是良性」",
    "   坏例子：「还钱约定」「宠物看病」「检查结果」（太抽象，将来搜不到）",`;

const newRule2 = `    "2. **一条记忆 = 一件事**，不是一段对话。",
    "   title 写这件事本身，不要写「谁说/谁问」。",
    "   好：「小雨是群友给凝起的绰号」「凝答应进修中文」「架构改了十二小时还没理清」",
    "   坏：「他说小雨」「vee说架构乱」「凝说好」（那是对话流水，不是事）",
    "   title 要带检索词：具体人名、物件、金额、日期、结论。",`;

if (s.includes(oldRule2)) {
  s = s.replace(oldRule2, newRule2);
  console.log("规则 2 已改成「一件事」");
}

const oldRule3 = `    "3. detail 写清发生了什么就行，不用逐字照抄；但数字、日期、人名、地点、结论必须准确。",`;

const newRule3 = `    "3. detail 写**这件事的经过**，不是对话摘录：谁做了什么、为什么、结果怎样。",
    "   不要「他说…然后她说…」地复述。数字、日期、人名、地点、结论必须准确。",
    "   反例：「他说凝的架构乱，凝说好，他说明天再干」（这是流水）",
    "   正例：「他 折腾了一整天凝的记忆架构，到晚上还是理不清，决定先去睡，明天再继续」（这是一件事）",
    "   同一天里同一件事只记一条；不同的事分开记。",`;

if (s.includes(oldRule3)) {
  s = s.replace(oldRule3, newRule3);
  console.log("规则 3 已改成「写经过」");
}

// 名字：不许再出现「主人」
s = s.replace(
  '    "    上面标了每句话是谁说的：__X__。",',
  '    "    上面标了每句话是谁说的：__X__。",',
);

writeFileSync(p, s, "utf8");
console.log("done");
